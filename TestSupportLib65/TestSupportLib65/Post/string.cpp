char* strstr(const char* sz, const char* szFind)
{
size_t uiFind;
size_t uiLength;
const char* pc;
uiFind = strlen(szFind);
if (uiFind == 0)
{
return (char*)sz;
}
uiLength = strlen(sz);
while (uiLength >= uiFind)
{
pc = (const char*)memchr(sz, szFind[0], uiLength - uiFind + 1);
if (!pc)
{
return 0L;
}
uiLength -= pc - sz;
sz = pc;
if (memcmp(sz, szFind, uiFind) == 0)
{
return (char*)sz;
}
sz++;
uiLength--;
}
return 0L;
}
