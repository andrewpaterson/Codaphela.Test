{
if (sizeof(int) == 2)
{
return PT_int16;
}
else if (sizeof(int) == 4)
{
return PT_int32;
}
else if (sizeof(int) == 8)
{
return PT_int64;
}
else if (sizeof(int) == 1)
{
return PT_int8;
}
return PT_Undefined;
}
