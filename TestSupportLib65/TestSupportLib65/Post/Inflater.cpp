bool CInflater::ReadZLibHeader(void)
{
uint8 uiMethod;
uint8 uiFlags;
if (!mpcInput->ReadInt8(&uiMethod) || !mpcInput->ReadInt8(&uiFlags))
{
return false;
}
if ((((uiMethod << 8) | uiFlags) % 31) != 0)
{
return false;
}
if (((uiMethod & 0xF) != 8) || ((uiMethod >> 4) > 7))
{
return false;
}
return (uiFlags & 0x20) == 0;
}
